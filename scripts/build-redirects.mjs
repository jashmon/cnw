// Builds src/content/redirects.ts (301s) from: catalogue `sources` (old PHP pages + PDFs), the audit's old-URL
// inventory (03-audit/audit.md tables) and the copy deck's category slugs. Unmatched old URLs are written to
// 05-architecture/redirects-unmatched.txt. Run after scripts/sync-content.mjs.
import fs from "node:fs";
import path from "node:path";

const site = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const proj = path.resolve(site, "..");
const data = (f, fb) => { try { return JSON.parse(fs.readFileSync(path.join(site, "src/content/data", f), "utf8")); } catch { return fb; } };
const cat = data("catalogue.json", []);
const voice = new Map(data("products.json", []).map((v) => [v.slug, v]));
const catsRaw = data("categories.json", []);
const cats = Array.isArray(catsRaw) ? catsRaw : (catsRaw.families ?? []).flatMap((f) => f.categories ?? []);
const slugify = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const catSlug = (p) => cats.find((c) => c.name === (voice.get(p.slug)?.category ?? p.category))?.slug ?? voice.get(p.slug)?.categorySlug ?? slugify(p.category);
const url = (p) => `/products/${catSlug(p)}/${p.slug}`;
const norm = (s) => s.toLowerCase().replace(/\.php$/, "").replace(/[^a-z0-9]/g, "");

const map = new Map(); // old path → destination
const add = (old, dest) => { if (!old.startsWith("/")) old = "/" + old; if (!map.has(old)) map.set(old, dest); };

// 1. catalogue sources
for (const p of cat) for (const s of p.sources ?? []) {
  const base = path.basename(s);
  if (s.endsWith(".php")) add(base, url(p));
  else if (s.endsWith(".pdf")) {
    const rel = s.replace(/^(cnwcom|voizlink)\//, "");
    add(rel, p.pdf === s || fs.existsSync(path.join(site, "public/files/datasheets", `${p.slug}.pdf`)) ? `/files/datasheets/${p.slug}.pdf` : url(p));
  }
}
// manual: dead homepage link on voizlink (500 today) — the weigh-log totaliser is BC-L01
const bcl01 = cat.find((p) => p.slug === "bc-l01"); if (bcl01) add("/voizlink-weight-log-bag-counter-amp-totaliser-unit-111.php", url(bcl01));
// 2. audit inventory
const audit = fs.readFileSync(path.join(proj, "03-audit/audit.md"), "utf8");
const rows = [...audit.matchAll(/^\|\s*\d+\s*\|\s*`([^`]+)`\s*\|\s*(\w+)/gm)].map((m) => ({ p: m[1], type: m[2] }));
const models = cat.filter((p) => p.model).map((p) => ({ p, k: norm(p.model) })).sort((a, b) => b.k.length - a.k.length);
const info = [
  [/about|corporate|ceo|director/i, "/about"], [/contact/i, "/contact"], [/^\/index\d*\.(php|html)$/i, "/"], [/video/i, "/downloads#videos"],
  [/ppt|presentation/i, "/systems"], [/our-equipments|located-industries/i, "/installed-at"], [/download/i, "/downloads"], [/catalog|catalogue/i, "/products"],
  [/products\.html|index2|index3/i, "/products"], [/inquiry|callrequest|emailfire|submitrequest/i, "/contact"], [/ECB\.php/i, "/products/emergency-call-boxes"],
];
const unmatched = [];
for (const { p, type } of rows) {
  if (map.has(p)) continue;
  const n = norm(path.basename(p));
  const hit = models.find(({ k }) => k.length >= 3 && n.includes(k));
  if (hit && type !== "info") { add(p, url(hit.p)); continue; }
  const i = info.find(([re]) => re.test(p));
  if (i) { add(p, i[1]); continue; }
  if (hit) { add(p, url(hit.p)); continue; }
  unmatched.push(`${p}\t${type}`);
}
// 3. emit: raw + %20-encoded variants; escape path-to-regexp specials
const esc = (s) => s.replace(/[()?*+:{}!]/g, (c) => "\\" + c);
const out = [];
for (const [old, dest] of map) {
  if (old === dest) continue;
  const variants = new Set([old, encodeURI(old)]);
  for (const v of variants) out.push({ source: esc(v), destination: dest, permanent: true });
}
fs.writeFileSync(path.join(site, "src/content/redirects.ts"), `// Generated by scripts/build-redirects.mjs — do not edit by hand.\nexport const legacyRedirects: { source: string; destination: string; permanent: boolean }[] = ${JSON.stringify(out, null, 1)};\n`);
fs.writeFileSync(path.join(proj, "05-architecture/redirects-unmatched.txt"), unmatched.join("\n") + "\n");
fs.writeFileSync(path.join(proj, "05-architecture/redirects.csv"), "old,new\n" + [...map].map(([a, b]) => `"${a}","${b}"`).join("\n") + "\n");
console.log(`${map.size} old URLs → ${out.length} rules; ${unmatched.length} unmatched`);
